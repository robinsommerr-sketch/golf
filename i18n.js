  const enToNo = new Map(EN_NO), noToEn = new Map(EN_NO.map(([en,no])=>[no,en]));
  // Translation keys are only exact UI strings, NOT arbitrary player text.
  const attrs = ['placeholder','title','aria-label'];
  const origins = new WeakMap();
  const ignored = '.chat-message-content, .chat-message-text, .chat-body, .message-body, .profile-bio, [data-i18n-ignore], [contenteditable], script, style, textarea, .log-body, .chat-list .message-text, .player-message-text, .chat-message-top strong, .context-line, #banReason, .social-list-info strong, #profile-name, #socialMyName, .leaderboard-name, .profile-bio, .moderation-detail blockquote, .moderation-detail > p, #adminChatResults .social-list-info small';
  let lang = (() => { try { return localStorage.getItem('fc_lang') === 'no' ? 'no' : 'en'; } catch { return 'en'; } })();
  const rx = templates.map(([pattern,en,no]) => [new RegExp(pattern),en,no]);
  const capture = (tpl,m) => tpl.replace(/\$(\d+)/g,(_,i)=>m[Number(i)]??'');
  function convert(value,target=lang){
    if(typeof value!=='string' || !value.trim())return value;
    const trimmed=value.trim();
    let result;
    if(target==='en') result=noToEn.get(trimmed) ?? (enToNo.has(trimmed) ? trimmed : null);
    else result=enToNo.get(trimmed) ?? (noToEn.has(trimmed) ? trimmed : null);
    if(result==null){
      for(const [matcher,en,no] of rx){
        const match=trimmed.match(matcher);
        if(match){result=capture(target==='en'?en:no,match);break;}
      }
    }
    if(result==null||result===trimmed)return value;
    return value.replace(trimmed,result);
  }
  function excluded(node){const parent=node.nodeType===3?node.parentElement:node;return !parent || Boolean(parent.closest(ignored));}
  function translateTextNode(node){
    if(excluded(node))return;
    const value=node.nodeValue, cached=origins.get(node);
    const original=cached && cached.last===value ? cached.original : value;
    const next=convert(original);
    origins.set(node,{original,last:next});
    if(next!==value)node.nodeValue=next;
  }
  function translateElement(el){
    if(!(el instanceof Element)||excluded(el))return;
    for(const attr of attrs){if(el.hasAttribute(attr)){const cur=el.getAttribute(attr),next=convert(cur);if(next!==cur)el.setAttribute(attr,next)}}
  }
  function translateTree(node){
    if(node.nodeType===3){translateTextNode(node);return;}
    if(node.nodeType!==1 && node.nodeType!==9 && node.nodeType!==11)return;
    if(node.nodeType===1)translateElement(node);
    const walk=document.createTreeWalker(node,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
    let current;while((current=walk.nextNode())){if(current.nodeType===3)translateTextNode(current);else translateElement(current)}
  }
  function refreshButtons(){
    document.documentElement.lang=lang==='no'?'no':'en';
    for(const b of document.querySelectorAll('[data-language]')){
      const chosen=b.dataset.language===lang;
      b.classList.toggle('selected',chosen);b.setAttribute('aria-pressed',String(chosen));
    }
  }
  function setLanguage(next){
    if(next!=='en'&&next!=='no')return;
    lang=next;
    try{localStorage.setItem('fc_lang',next)}catch{}
    refreshButtons();translateTree(document.body);
    document.dispatchEvent(new CustomEvent('fairway:languagechange',{detail:{language:lang}}));
  }
  // Follow app.js and social.js rerenders, including toasts and scorecards.
  const observer=new MutationObserver(changes=>{
    for(const change of changes){
      if(change.type==='characterData')translateTextNode(change.target);
      else for(const node of change.addedNodes)translateTree(node);
    }
  });
  for(const b of document.querySelectorAll('[data-language]'))b.addEventListener('click',()=>setLanguage(b.dataset.language));
  refreshButtons();translateTree(document.body);
  observer.observe(document.body,{childList:true,characterData:true,subtree:true});
